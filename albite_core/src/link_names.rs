/// Prefixes the toolchain owns. `tg_` is the runtime archive's own
/// namespace; `__` covers `__albite_*` (the runtime's hooks), `__wrap_*`
/// (an extern's wrapper, `extern_naming.rs`) and every name C reserves for
/// the implementation — as does `_` before an uppercase letter, which
/// [`is_reserved_link_name`] checks beside these.
pub const RESERVED_LINK_PREFIXES: &[&str] = &["tg_", "__"];

/// Whether `name`, as a C symbol, is one a program's definition must not
/// take: listed, under a reserved prefix, or `_` + an uppercase letter.
#[must_use]
pub fn is_reserved_link_name(name: &str) -> bool {
    RESERVED_LINK_NAMES.binary_search(&name).is_ok()
        || RESERVED_LINK_PREFIXES
            .iter()
            .any(|prefix| name.starts_with(prefix))
        || reserved_by_c_underscore_rule(name)
}

/// C11 7.1.3: an identifier beginning `_` and an uppercase letter is
/// reserved for any use (`_Exit`, `_Unwind_Resume`, `_NSGetArgv`).
fn reserved_by_c_underscore_rule(name: &str) -> bool {
    let mut chars = name.chars();
    chars.next() == Some('_') && chars.next().is_some_and(|c| c.is_ascii_uppercase())
}

